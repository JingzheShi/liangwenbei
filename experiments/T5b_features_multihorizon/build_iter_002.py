"""Build iter_002 submission package after LOSO training + threshold sweep.

Strategy: include in iter_002 every horizon whose LOSO best (T, delta) sum is
positive. For each chosen horizon:
  - copy final_model_h{H}.txt (trained on full train+val, not LOSO)
  - record (T, delta) into thresholds.json
Other horizons remain inactive (output 1 / flat).

Reads:
  experiments/T5b_features_multihorizon/threshold_results.json
  experiments/T5b_features_multihorizon/final_model_h{H}.txt    (must exist)

Writes:
  submission/iter_002_lgbm_schemeC/model_h{H}.txt   (one per active horizon)
  submission/iter_002_lgbm_schemeC/thresholds.json
"""
from __future__ import annotations

import argparse
import json
import os
import shutil
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))
SUBMIT_DIR = os.path.join(ROOT, "submission", "iter_002_lgbm_schemeC")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--min-sum", type=float, default=0.0,
                    help="minimum LOSO best sum_cum_pnl to include a horizon")
    ap.add_argument("--force-horizons", default="",
                    help="comma-separated horizons to FORCE include even if min-sum not met")
    args = ap.parse_args()

    sweep_path = os.path.join(HERE, "threshold_results.json")
    if not os.path.isfile(sweep_path):
        sys.exit(f"missing {sweep_path} — run threshold_sweep.py first")
    with open(sweep_path) as f:
        sweep = json.load(f)

    force_set = set()
    if args.force_horizons.strip():
        force_set = set(int(x) for x in args.force_horizons.split(","))

    # Decide active horizons
    horizons_in = []
    for row in sweep["summary_rows"]:
        h = int(row["horizon"])
        best_sum = float(row["best_sum_cum_pnl"])
        active = best_sum >= args.min_sum or h in force_set
        horizons_in.append({
            "h": h,
            "T": float(row["best_T"]),
            "delta": float(row["best_delta"]),
            "loso_best_sum": best_sum,
            "loso_n_pos_folds": int(row["best_n_pos_folds"]),
            "raw_argmax_sum": float(row["baseline_sum"]),
            "active": bool(active),
        })

    active_hs = [h["h"] for h in horizons_in if h["active"]]
    print(f"Active horizons: {active_hs}")
    if not active_hs:
        print("No active horizons — defaulting to label_60 with neutral threshold")
        # Fallback: at least include h=60 with T=0.5 d=0.15
        for h in horizons_in:
            if h["h"] == 60:
                h["active"] = True
                h["T"] = 0.50
                h["delta"] = 0.15
                active_hs = [60]
                break

    # Copy models
    os.makedirs(SUBMIT_DIR, exist_ok=True)
    for H in active_hs:
        src = os.path.join(HERE, f"final_model_h{H}.txt")
        dst = os.path.join(SUBMIT_DIR, f"model_h{H}.txt")
        if not os.path.isfile(src):
            sys.exit(f"missing final model: {src} — run train_final.py --horizons={H} first")
        shutil.copy(src, dst)
        print(f"copied {src} -> {dst}")
    # Remove inactive model files (in case from previous build)
    for H in (5, 10, 20, 40, 60):
        if H not in active_hs:
            mp = os.path.join(SUBMIT_DIR, f"model_h{H}.txt")
            if os.path.isfile(mp):
                os.remove(mp)
                print(f"removed stale {mp}")

    # Strip non-essentials from horizons_in for thresholds.json
    horizons_clean = []
    for h in horizons_in:
        horizons_clean.append({
            "h": h["h"],
            "T": h["T"],
            "delta": h["delta"],
            "active": h["active"],
            "loso_best_sum": h["loso_best_sum"],
            "loso_n_pos_folds": h["loso_n_pos_folds"],
            "raw_argmax_sum": h["raw_argmax_sum"],
        })

    out_path = os.path.join(SUBMIT_DIR, "thresholds.json")
    with open(out_path, "w") as f:
        json.dump({
            "_doc": "iter_002 multi-horizon thresholds. Generated by build_iter_002.py.",
            "horizons": horizons_clean,
        }, f, indent=2)
    print(f"thresholds -> {out_path}")
    print("\n=== Summary ===")
    for h in horizons_clean:
        flag = "ACTIVE" if h["active"] else "flat"
        print(f"  h={h['h']:2d}: {flag} (T={h['T']:.2f} d={h['delta']:.2f}) "
              f"LOSO best sum={h['loso_best_sum']:+.3f} pos={h['loso_n_pos_folds']}/5 "
              f"raw_sum={h['raw_argmax_sum']:+.3f}")


if __name__ == "__main__":
    main()
