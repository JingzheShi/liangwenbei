"""Build iter_004 submission package: 5-seed ensemble Scheme C 223-d, multi-horizon.

Reads:
    experiments/T11_schemeC_multiseed/threshold_results.json   per-horizon best (T,delta)
    experiments/T11_schemeC_multiseed/final_223_model_h{H}_seed{S}.txt   for each (S, H)

Writes:
    submission/iter_004_lgbm_schemeC_ensemble/
        Predictor.py            (multi-seed ensemble)
        compute.py              (T3 features, copied from iter_002)
        config.json             (copied from iter_002 = 154 raw cols)
        requirements.txt        (numpy/pandas/lightgbm pinned)
        thresholds.json         per-horizon (T, delta) + active flag + seed list
        model_h{H}_seed{S}.txt  for each seed and active horizon
"""
from __future__ import annotations

import argparse
import json
import os
import shutil
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))
SUBMIT_DIR = os.path.join(ROOT, "submission", "iter_004_lgbm_schemeC_ensemble")
ITER002_DIR = os.path.join(ROOT, "submission", "iter_002_lgbm_schemeC")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--seeds", default="42,1,7,13,100")
    ap.add_argument("--horizons", default="10",
                    help="comma-separated horizons to include")
    ap.add_argument("--min-sum", type=float, default=0.0,
                    help="minimum LOSO ensemble best sum_cum_pnl to keep horizon active")
    args = ap.parse_args()

    horizons = [int(x) for x in args.horizons.split(",")]
    seeds = [int(x) for x in args.seeds.split(",")]
    print(f"Building iter_004 — horizons={horizons} seeds={seeds}")

    sweep_path = os.path.join(HERE, "threshold_results.json")
    if not os.path.isfile(sweep_path):
        sys.exit(f"missing {sweep_path}")
    with open(sweep_path) as f:
        sweep = json.load(f)

    os.makedirs(SUBMIT_DIR, exist_ok=True)

    # Copy unchanged auxiliaries from iter_002
    for fn in ("compute.py", "config.json", "requirements.txt"):
        src = os.path.join(ITER002_DIR, fn)
        dst = os.path.join(SUBMIT_DIR, fn)
        shutil.copy(src, dst)
        print(f"copied {src} -> {dst}")

    # Copy Predictor.py from this experiment dir (rewrite below)
    predictor_src = os.path.join(HERE, "Predictor.py")
    predictor_dst = os.path.join(SUBMIT_DIR, "Predictor.py")
    if not os.path.isfile(predictor_src):
        sys.exit(f"missing {predictor_src} (write the ensemble Predictor first)")
    shutil.copy(predictor_src, predictor_dst)
    print(f"copied {predictor_src} -> {predictor_dst}")

    # Build thresholds.json (only with horizons we have models for)
    horizons_in = []
    valid_hs = set(int(h.lstrip("h")) for h in sweep["per_horizon"].keys())
    print(f"  thresholds available for horizons: {sorted(valid_hs)}")

    for H in horizons:
        if H not in valid_hs:
            sys.exit(f"horizon h={H} not in threshold_results.json")
        ens = sweep["per_horizon"][f"h{H}"]["ensemble"]
        best_sum = float(ens["best"]["sum_cum_pnl"])
        active = best_sum >= args.min_sum
        horizons_in.append({
            "h": H,
            "T": float(ens["best"]["T"]),
            "delta": float(ens["best"]["delta"]),
            "active": bool(active),
            "loso_ensemble_best_sum": best_sum,
            "loso_ensemble_n_pos_folds": int(ens["best"]["n_pos_folds"]),
            "loso_ensemble_argmax_sum": float(ens["baseline"]["raw_argmax_sum_cum_pnl"]),
        })

    active_hs = [h["h"] for h in horizons_in if h["active"]]
    if not active_hs:
        sys.exit("no horizons active — abort")

    # Copy seed models for each active horizon
    for H in active_hs:
        for s in seeds:
            src = os.path.join(HERE, f"final_223_model_h{H}_seed{s}.txt")
            dst = os.path.join(SUBMIT_DIR, f"model_h{H}_seed{s}.txt")
            if not os.path.isfile(src):
                sys.exit(f"missing final model: {src}")
            shutil.copy(src, dst)
            print(f"copied {src} -> {os.path.basename(dst)}")

    # Remove stale model files (from previous build)
    for fn in os.listdir(SUBMIT_DIR):
        if fn.startswith("model_h") and fn.endswith(".txt"):
            # Decode "model_hH_seedS.txt"
            keep = False
            for H in active_hs:
                for s in seeds:
                    if fn == f"model_h{H}_seed{s}.txt":
                        keep = True; break
                if keep: break
            if not keep:
                p = os.path.join(SUBMIT_DIR, fn)
                os.remove(p)
                print(f"removed stale {p}")

    out_th = os.path.join(SUBMIT_DIR, "thresholds.json")
    with open(out_th, "w") as f:
        json.dump({
            "_doc": "iter_004 multi-seed ensemble thresholds. Generated by build_iter_004.py.",
            "seeds": seeds,
            "horizons": horizons_in,
        }, f, indent=2)
    print(f"thresholds -> {out_th}")
    print("\n=== Summary ===")
    for h in horizons_in:
        flag = "ACTIVE" if h["active"] else "flat"
        print(f"  h={h['h']:2d}: {flag} (T={h['T']:.2f} d={h['delta']:.2f})  "
              f"LOSO ens best={h['loso_ensemble_best_sum']:+.3f} "
              f"pos={h['loso_ensemble_n_pos_folds']}/5  "
              f"argmax={h['loso_ensemble_argmax_sum']:+.3f}")


if __name__ == "__main__":
    main()
